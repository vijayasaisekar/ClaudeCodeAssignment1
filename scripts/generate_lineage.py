#!/usr/bin/env python3
"""
Generates outputs/artifacts/FEATURE_LINEAGE.md from features/schema.py and the feature store
registry. One entry per feature per registered version, so every stored version appears
separately with its own parameters, rationale and parquet path.

Run from the repo root, after build_training_features:

    python -m scripts.generate_lineage
"""

from pathlib import Path

from feature_store import store
from features.schema import FEATURE_SCHEMA

OUTPUT_PATH = Path("outputs/artifacts/FEATURE_LINEAGE.md")


def _entry(spec, row) -> list[str]:
    latest_flag = "yes" if row.is_latest == 1 else "no"
    return [
        f"#### {spec.name} — version {row.version}",
        "",
        f"- **Registry location:** `feature_store/registry.db`, table `feature_registry`, "
        f"`feature_name = '{row.feature_name}'`, `version = {row.version}`",
        f"- **Parquet snapshot:** `{row.parquet_path}`",
        f"- **is_latest:** {latest_flag}",
        f"- **Parameters:** `{row.parameters}`",
        f"- **Source(s):** `{row.source_columns}`",
        f"- **Source justification:** {spec.source_justification}",
        f"- **Transform:** {row.transform_summary}",
        f"- **Zero-activity default:** {spec.zero_activity_default}",
        f"- **Business rationale for this version:** {row.business_rationale}",
        f"- **Feature rationale:** {spec.rationale}",
        f"- **Registered at:** {row.created_at}",
        "",
    ]


def main() -> None:
    registry = store.list_all_versions()
    out = [
        "# FEATURE_LINEAGE.md",
        "",
        "Generated by `scripts/generate_lineage.py` from `features/schema.py` and "
        "`feature_store/registry.db`. Do not edit by hand; regenerate after a build.",
        "",
        "## Summary",
        "",
        "| feature | dtype | nullable | versions registered | latest version | versioned |",
        "|---|---|---|---|---|---|",
    ]
    for spec in FEATURE_SCHEMA:
        rows = registry[registry["feature_name"] == spec.name]
        latest = int(rows.loc[rows["is_latest"] == 1, "version"].iloc[0]) if len(rows) else None
        out.append(
            f"| {spec.name} | {spec.dtype} | {spec.nullable} | {len(rows)} | "
            f"{latest} | {'yes' if spec.is_versioned else 'no'} |"
        )
    out.append("")

    out += ["## Features", ""]
    for spec in FEATURE_SCHEMA:
        out += [f"### {spec.name}", "", spec.description, ""]
        rows = registry[registry["feature_name"] == spec.name]
        if rows.empty:
            out += ["**Not registered.** Run `scripts/build_training_features.py`.", ""]
            continue
        for row in rows.itertuples():
            out += _entry(spec, row)

    OUTPUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT_PATH.write_text("\n".join(out), encoding="utf-8")
    print(f"Wrote {OUTPUT_PATH}: {len(registry)} registered version(s) across {len(FEATURE_SCHEMA)} features.")


if __name__ == "__main__":
    main()
