#!/usr/bin/env python3
"""
Parity-mutation check. Copies the code into a scratch directory, deliberately reintroduces a
training/scoring split there, and confirms tests/test_parity.py fails. The real repo is never
modified. Writes outputs/artifacts/PARITY_CHECK.md.

Run from the repo root:

    python -m scripts.parity_mutation_check
"""

import hashlib
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
OUTPUT_PATH = REPO / "outputs" / "artifacts" / "PARITY_CHECK.md"
COPY_ITEMS = ["features", "feature_store", "tests", "data", "pytest.ini"]
TARGET = Path("features") / "build.py"

ORIGINAL_LINE = (
    "    columns = {spec.name: compute_feature(spec.name, as_of, sources, ids) for spec in FEATURE_SCHEMA}\n"
)
MUTATED_BLOCK = (
    "    columns = {}\n"
    "    for spec in FEATURE_SCHEMA:\n"
    "        params = spec.latest.params\n"
    "        if customer_ids is not None and spec.name == \"spend_prior_winsorized\":  # MUTATION: scoring-only cap\n"
    "            params = {**params, \"cap_amount\": 250.0}\n"
    "        columns[spec.name] = compute_feature(spec.name, as_of, sources, ids, params=params)\n"
)


def _sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def _pytest(cwd: Path, targets: list[str]) -> tuple[int, str]:
    proc = subprocess.run(
        [sys.executable, "-m", "pytest", "-v", *targets],
        cwd=cwd,
        capture_output=True,
        text=True,
        encoding="utf-8",
        errors="replace",
    )
    return proc.returncode, proc.stdout + proc.stderr


def _summary_line(output: str) -> str:
    lines = [line for line in output.splitlines() if " passed" in line or " failed" in line or "error" in line.lower()]
    return lines[-1].strip("= ") if lines else "(no summary line)"


def _failed_tests(output: str) -> list[str]:
    return sorted({line.split()[0] for line in output.splitlines() if line.startswith("tests/") and "FAILED" in line})


def main() -> None:
    target_before = _sha256(REPO / TARGET)
    baseline_code, baseline_out = _pytest(REPO, ["tests/test_parity.py"])

    scratch = Path(tempfile.mkdtemp(prefix="parity_mutation_"))
    try:
        for item in COPY_ITEMS:
            src = REPO / item
            dst = scratch / item
            if src.is_dir():
                # Skip the generated registry and snapshots; the raw data/*.db must be copied.
                shutil.copytree(src, dst, ignore=shutil.ignore_patterns("__pycache__", "registry.db", "values"))
            else:
                shutil.copy2(src, dst)

        mutated_file = scratch / TARGET
        source = mutated_file.read_text(encoding="utf-8")
        occurrences = source.count(ORIGINAL_LINE)
        if occurrences != 1:
            raise RuntimeError(f"Mutation anchor found {occurrences} times in {TARGET}; expected exactly 1")
        mutated_file.write_text(source.replace(ORIGINAL_LINE, MUTATED_BLOCK), encoding="utf-8")

        mutated_code, mutated_out = _pytest(scratch, ["tests/test_parity.py"])
    finally:
        shutil.rmtree(scratch, ignore_errors=True)

    target_after = _sha256(REPO / TARGET)
    if target_before != target_after:
        raise RuntimeError("Repo features/build.py changed during the check; aborting")

    # Count as caught only when the parity comparison itself fails with an assertion. A crash from
    # the environment (for example a missing data file) must not be mistaken for a caught divergence.
    caught = (
        mutated_code != 0
        and any("test_training_and_scoring_paths_agree_for_same_customer" in name for name in _failed_tests(mutated_out))
        and "AssertionError" in mutated_out
        and "DatabaseError" not in mutated_out
    )
    verdict = "CAUGHT" if caught else "NOT CAUGHT"

    lines = [
        "# PARITY_CHECK.md",
        "",
        "Generated by `scripts/parity_mutation_check.py`. The check copies `features/`, `feature_store/`, "
        "`tests/`, `data/` and `pytest.ini` into a scratch directory, injects the mutation below into the "
        "scratch copy only, and runs `tests/test_parity.py` in both trees. The repo is not modified.",
        "",
        "## Result",
        "",
        f"**Verdict: {verdict}.** The injected training/scoring divergence "
        + ("is caught by" if caught else "is NOT caught by")
        + " `test_training_and_scoring_paths_agree_for_same_customer`.",
        "",
        "| run | tree | exit code | summary |",
        "|---|---|---|---|",
        f"| baseline | real repo (unmodified) | {baseline_code} | {_summary_line(baseline_out)} |",
        f"| mutated | scratch copy with mutation | {mutated_code} | {_summary_line(mutated_out)} |",
        "",
        "## Mutation applied (scratch copy only)",
        "",
        f"Target: `{TARGET.as_posix()}`, function `build_features`. The mutation adds a scoring-only "
        "override of the spend cap. It applies only when `customer_ids` is passed (the scoring path), so "
        "training and scoring compute the same feature differently.",
        "",
        "Original line:",
        "",
        "```python",
        ORIGINAL_LINE.rstrip("\n"),
        "```",
        "",
        "Replaced with:",
        "",
        "```python",
        MUTATED_BLOCK.rstrip("\n"),
        "```",
        "",
        "## Tests that failed in the mutated run",
        "",
    ]
    failed = _failed_tests(mutated_out)
    lines += [f"- `{name}`" for name in failed] if failed else ["- none"]
    lines += [
        "",
        "## Repo integrity",
        "",
        f"`features/build.py` SHA-256 before: `{target_before}`",
        f"`features/build.py` SHA-256 after:  `{target_after}`",
        "The two values match, so the real file was not changed by the check.",
        "",
        "## Mutated run output (tail)",
        "",
        "```",
        "\n".join(mutated_out.strip().splitlines()[-25:]),
        "```",
        "",
    ]

    OUTPUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT_PATH.write_text("\n".join(lines), encoding="utf-8")
    print(f"Verdict: {verdict}. Wrote {OUTPUT_PATH}")
    if not caught:
        raise SystemExit(1)


if __name__ == "__main__":
    main()
